// Reads the fonts in assets/fonts and writes them into src/generator/embedded-fonts.ts as base64,
// so they are always part of the build (also on Vercel). Run:  npm run embed-fonts
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const FILES = {
  latin: 'NotoSans-Regular.ttf',
  latinBold: 'NotoSans-Bold.ttf',
  latinItalic: 'NotoSans-Italic.ttf',
  latinBoldItalic: 'NotoSans-BoldItalic.ttf',
  bn: 'NotoSansBengali-Regular.ttf',
  bnBold: 'NotoSansBengali-Bold.ttf',
};

const dir = join(process.cwd(), 'assets', 'fonts');
const lines = [];

for (const [key, file] of Object.entries(FILES)) {
  const path = join(dir, file);
  if (existsSync(path)) {
    const bytes = readFileSync(path);
    lines.push(`  ${key}: '${bytes.toString('base64')}',`);
    console.log(`embedded  ${file} (${Math.round(bytes.length / 1024)} KB)`);
  } else {
    console.log(`missing   ${file}`);
  }
}

const out = `// Generated by scripts/embed-fonts.mjs (npm run embed-fonts). Do not edit by hand.
export const EMBEDDED_FONTS: Partial<Record<string, string>> = {
${lines.join('\n')}
};
`;
writeFileSync(join(process.cwd(), 'src', 'generator', 'embedded-fonts.ts'), out);
console.log('\nWrote src/generator/embedded-fonts.ts');